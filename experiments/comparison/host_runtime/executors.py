def _extract_python_code(text: str) -> str:
    fence = re.search(r"```(?:python)?\s*(.*?)```", text, flags=re.IGNORECASE | re.DOTALL)
    code = fence.group(1) if fence else text
    code = code.strip()
    if not code:
        raise RuntimeError("LLM returned empty code.")
    return code + "\n"


def _ensure_required_stdlib_imports(code: str) -> str:
    try:
        tree = ast.parse(code)
    except SyntaxError:
        return code

    uses_os_name = any(isinstance(node, ast.Name) and node.id == "os" for node in ast.walk(tree))
    if not uses_os_name or _has_imported_module(tree, "os"):
        return code

    lines = code.splitlines()
    insert_at = 0
    while insert_at < len(lines) and (
        lines[insert_at].startswith("#!") or "coding" in lines[insert_at].lower()
    ):
        insert_at += 1
    while insert_at < len(lines) and lines[insert_at].startswith("from __future__ import "):
        insert_at += 1
    lines.insert(insert_at, "import os")
    return "\n".join(lines).rstrip() + "\n"


def _has_imported_module(tree: ast.AST, module_name: str) -> bool:
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.split(".", 1)[0] == module_name:
                    return True
    return False


def _validate_llm_code(code: str) -> None:
    hits: list[str] = []
    try:
        tree = ast.parse(code)
    except SyntaxError:
        return

    forbidden_import_roots = {"subprocess", "requests", "httpx", "urllib", "socket"}
    forbidden_env_vars = {"PROJ_LIB", "PROJ_DATA", "GDAL_DATA"}
    unsupported_imports = {
        "matplotlib._contour": "Use skimage.measure.find_contours or public matplotlib contour APIs.",
        "rasterio.windows.window_transform": "Use rasterio.windows.transform(window, src.transform).",
        "rasterio.sample.sample": "Use src.sample(coords) or rasterio.sample.sample_gen.",
    }
    forbidden_calls = {
        "eval",
        "exec",
        "os.system",
        "os.remove",
        "os.unlink",
        "shutil.rmtree",
        "os.putenv",
    }
    forbidden_attrs = {"unlink", "rmdir"}

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                root = alias.name.split(".", 1)[0]
                if root in forbidden_import_roots:
                    hits.append(f"import:{root}")
                if alias.name in unsupported_imports:
                    hits.append(f"unsupported_api:{alias.name}")
        elif isinstance(node, ast.ImportFrom):
            module = node.module or ""
            root = module.split(".", 1)[0]
            if root in forbidden_import_roots:
                hits.append(f"import:{root}")
            for alias in node.names:
                full_name = f"{module}.{alias.name}" if module else alias.name
                if full_name in unsupported_imports:
                    hits.append(f"unsupported_api:{full_name}")
                if module == "matplotlib" and alias.name == "_contour":
                    hits.append("unsupported_api:matplotlib._contour")
        elif isinstance(node, ast.Call):
            call_name = _call_name(node.func)
            if call_name in forbidden_calls:
                hits.append(f"call:{call_name}")
            elif call_name.endswith(".union_all"):
                hits.append("unsupported_api:union_all")
            elif call_name == "rasterio.windows.window_transform":
                hits.append("unsupported_api:rasterio.windows.window_transform")
            elif call_name == "rasterio.sample.sample":
                hits.append("unsupported_api:rasterio.sample.sample")
            elif isinstance(node.func, ast.Attribute) and node.func.attr == "sample" and any(
                keyword.arg == "resampling" for keyword in node.keywords
            ):
                hits.append("unsupported_api:DatasetReader.sample(resampling=...)")
            elif isinstance(node.func, ast.Attribute) and node.func.attr in forbidden_attrs:
                hits.append(f"call:.{node.func.attr}")
            if call_name == "os.putenv" and node.args and _string_literal(node.args[0]) in forbidden_env_vars:
                hits.append("env:os.putenv")
            for arg in node.args[:2]:
                literal = _string_literal(arg)
                if literal and _is_relative_output_literal(literal):
                    hits.append(f"relative_output_path:{literal[:40]}")
        elif isinstance(node, (ast.Assign, ast.AnnAssign, ast.AugAssign)):
            targets = []
            if isinstance(node, ast.Assign):
                targets = list(node.targets)
            else:
                targets = [node.target]
            for target in targets:
                if _is_forbidden_env_assignment(target, forbidden_env_vars):
                    hits.append("env:os.environ")

    if re.search(r"\bpip\s+install\b", code, flags=re.IGNORECASE):
        hits.append("text:pip install")
    if re.search(r"(?<![A-Za-z0-9_])(?:output|outputs)[\\/]+workflow_steps\.json", code, flags=re.IGNORECASE):
        hits.append("text:relative workflow_steps.json")
    if re.search(r"\bmatplotlib\._contour\b", code):
        hits.append("unsupported_api:matplotlib._contour")
    if re.search(r"\.window_transform\s*\(", code):
        hits.append("unsupported_api:rasterio.windows.window_transform")
    if hits:
        raise RuntimeError(f"Generated code failed safety validation: {sorted(set(hits))}")


def _prepare_execution_env(python_executable: str) -> dict[str, str]:
    env = os.environ.copy()
    proj_data = _find_rasterio_proj_data(python_executable)
    if proj_data is not None:
        env.pop("PROJ_LIB", None)
        env["PROJ_DATA"] = str(proj_data)
        env["PROJ_NETWORK"] = "OFF"
    return env


def _find_rasterio_proj_data(python_executable: str) -> Path | None:
    exe_path = Path(python_executable).resolve(strict=False)
    prefixes: list[Path] = []
    if len(exe_path.parents) >= 2:
        prefixes.append(exe_path.parents[1])
    prefixes.append(Path(sys.prefix))

    for prefix in prefixes:
        candidate = prefix / "Lib" / "site-packages" / "rasterio" / "proj_data"
        if (candidate / "proj.db").is_file():
            return candidate
    return None


def _call_name(func: ast.AST) -> str:
    if isinstance(func, ast.Name):
        return func.id
    if isinstance(func, ast.Attribute):
        parent = _call_name(func.value)
        return f"{parent}.{func.attr}" if parent else func.attr
    return ""


def _string_literal(node: ast.AST) -> str | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return None


def _is_forbidden_env_assignment(target: ast.AST, forbidden_env_vars: set[str]) -> bool:
    if not isinstance(target, ast.Subscript):
        return False
    if _call_name(target.value) != "os.environ":
        return False
    return _string_literal(target.slice) in forbidden_env_vars


def _is_relative_output_literal(value: str) -> bool:
    normalized = value.replace("\\", "/").strip()
    normalized = normalized[2:] if normalized.startswith("./") else normalized
    if re.match(r"^[A-Za-z]:/", normalized) or normalized.startswith("/"):
        return False
    return normalized in {"output", "outputs"} or normalized.startswith("output/") or normalized.startswith("outputs/")


def _zero_token_usage() -> dict[str, int]:
    return {
        "prompt_tokens": 0,
        "completion_tokens": 0,
        "total_tokens": 0,
    }


def _normalize_token_usage(value: Any) -> dict[str, int]:
    if not isinstance(value, dict):
        return _zero_token_usage()
    prompt_tokens = _usage_int(value.get("prompt_tokens") or value.get("input_tokens"))
    completion_tokens = _usage_int(value.get("completion_tokens") or value.get("output_tokens"))
    total_tokens = _usage_int(value.get("total_tokens"))
    if total_tokens == 0:
        total_tokens = prompt_tokens + completion_tokens
    return {
        "prompt_tokens": prompt_tokens,
        "completion_tokens": completion_tokens,
        "total_tokens": total_tokens,
    }


def _usage_int(value: Any) -> int:
    if isinstance(value, bool) or value is None:
        return 0
    if isinstance(value, int):
        return max(0, value)
    if isinstance(value, float):
        return max(0, int(value))
    try:
        return max(0, int(str(value)))
    except (TypeError, ValueError):
        return 0


