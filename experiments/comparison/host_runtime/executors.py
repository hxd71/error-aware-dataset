class OpenAICompatibleExecutorBackend(MockExecutorBackend):
    backend_name = "openai_compatible_executor"
    backend_version = "0.1.0"

    def __init__(
        self,
        *,
        model: str,
        base_url: str,
        api_key: str,
        python_executable: str | None = None,
        timeout_seconds: int = 300,
        request_timeout_seconds: int = 120,
        temperature: float = 0,
    ) -> None:
        super().__init__(python_executable=python_executable, timeout_seconds=timeout_seconds)
        self.model = model
        self.base_url = base_url.rstrip("/")
        self.api_key = api_key
        self.request_timeout_seconds = request_timeout_seconds
        self.temperature = temperature

    def generate_code(
        self,
        *,
        task: BenchmarkTask,
        agent_kind: AgentKind,
        attempt_index: int,
        repair_instruction: dict[str, Any] | None,
        previous_code: str,
        previous_execution_log: str,
    ) -> str:
        return self.generate_code_with_usage(
            task=task,
            agent_kind=agent_kind,
            attempt_index=attempt_index,
            repair_instruction=repair_instruction,
            previous_code=previous_code,
            previous_execution_log=previous_execution_log,
        ).code

    def generate_code_with_usage(
        self,
        *,
        task: BenchmarkTask,
        agent_kind: AgentKind,
        attempt_index: int,
        repair_instruction: dict[str, Any] | None,
        previous_code: str,
        previous_execution_log: str,
    ) -> CodeGenerationResult:
        if not self.api_key:
            raise RuntimeError("LLM executor requires a non-empty API key.")
        prompt = _build_llm_prompt(
            task=task,
            agent_kind=agent_kind,
            attempt_index=attempt_index,
            repair_instruction=repair_instruction,
            previous_code=previous_code,
            previous_execution_log=previous_execution_log,
        )
        response_text, token_usage = self._chat_completion(prompt)
        try:
            code = _extract_python_code(response_text)
            code = _ensure_required_stdlib_imports(code)
            _validate_llm_code(code)
        except Exception as exc:
            raise CodeGenerationError(str(exc), token_usage=token_usage) from exc
        return CodeGenerationResult(code=code, token_usage=token_usage)

    def _chat_completion(self, prompt: str) -> tuple[str, dict[str, int]]:
        payload = {
            "model": self.model,
            "temperature": self.temperature,
            "messages": [
                {
                    "role": "system",
                    "content": (
                        "You are a GIS workflow coding agent. Return exactly one complete Python script. "
                        "Do not include explanations outside the code block. Never use subprocess, os.system, "
                        "network libraries, package installation, eval, exec, os.remove, os.unlink, pathlib unlink, "
                        "rmdir, shutil.rmtree, or override PROJ/GDAL environment variables. "
                        "Do not rely on osgeo/GDAL Python bindings in this environment; use installed Python GIS libraries. "
                        "Avoid unavailable GIS APIs: matplotlib._contour, rasterio.windows.window_transform, "
                        "rasterio.sample.sample, and GeoPandas/Shapely union_all; use public alternatives. "
                        "The output directory is empty for each attempt, so do not clean it. "
                        "If you use os.environ or other os APIs, include import os."
                    ),
                },
                {"role": "user", "content": prompt},
            ],
        }
        with httpx.Client(timeout=self.request_timeout_seconds) as client:
            response = client.post(
                f"{self.base_url}/chat/completions",
                headers={"Authorization": f"Bearer {self.api_key}", "Content-Type": "application/json"},
                json=payload,
            )
            response.raise_for_status()
            data = response.json()
        usage = _normalize_token_usage(data.get("usage", {}))
        return str(data["choices"][0]["message"]["content"]), usage


def create_executor_backend(
    *,
    backend: str,
    python_executable: str | None,
    timeout_seconds: int,
    model_config: dict[str, Any],
) -> ExecutorBackend:
    if backend == "mock":
        return MockExecutorBackend(python_executable=python_executable, timeout_seconds=timeout_seconds)
    if backend == "template":
        return TemplateExecutorBackend(python_executable=python_executable, timeout_seconds=timeout_seconds)
    if backend == "llm":
        return OpenAICompatibleExecutorBackend(
            model=str(model_config.get("model", "")),
            base_url=str(model_config.get("base_url", "")),
            api_key=str(model_config.get("api_key", "")),
            python_executable=python_executable,
            timeout_seconds=timeout_seconds,
            request_timeout_seconds=int(model_config.get("request_timeout_seconds", 120)),
            temperature=float(model_config.get("temperature", 0)),
        )
    raise ValueError(f"Unknown executor backend: {backend}")


def load_llm_model_config(
    *,
    config_path: Path | None,
    model: str,
    base_url: str,
    api_key_env: str,
    request_timeout_seconds: int,
    temperature: float,
) -> tuple[dict[str, Any], dict[str, Any]]:
    file_values: dict[str, str] = {}
    if config_path and config_path.is_file():
        parser = configparser.ConfigParser()
        parser.read(config_path, encoding="utf-8")
        if parser.has_section("LLM"):
            file_values = {
                "model": parser.get("LLM", "MODEL", fallback=""),
                "base_url": parser.get("LLM", "OPENAI_BASE_URL", fallback=""),
                "api_key": parser.get("LLM", "DEEPSEEK_API_KEY", fallback="")
                or parser.get("LLM", "API_KEY", fallback=""),
            }
    api_key = os.environ.get(api_key_env, "") or file_values.get("api_key", "")
    resolved = {
        "provider": "openai-compatible",
        "model": model or file_values.get("model") or os.environ.get("COMPARISON_LLM_MODEL", "deepseek-v4-pro"),
        "base_url": base_url or file_values.get("base_url") or os.environ.get("OPENAI_BASE_URL", ""),
        "api_key": api_key,
        "request_timeout_seconds": request_timeout_seconds,
        "temperature": temperature,
    }
    trace_safe = dict(resolved)
    trace_safe.pop("api_key", None)
    trace_safe["api_key_env"] = api_key_env
    trace_safe["api_key_present"] = bool(api_key)
    return resolved, trace_safe


def _run_python_code(
    *,
    python_executable: str,
    code_path: Path,
    output_path: Path,
    task: BenchmarkTask,
    repair_instruction: dict[str, Any] | None,
    previous_output_path: Path | None,
    timeout_seconds: int,
) -> CodeExecutionResult:
    env = _prepare_execution_env(python_executable)
    env["OUTPUT_DIR"] = str(output_path.resolve(strict=False))
    if previous_output_path is not None:
        env["PREVIOUS_OUTPUT_DIR"] = str(previous_output_path.resolve(strict=False))
    env["TASK_JSON"] = json.dumps(task.agent_view(), ensure_ascii=False)
    env["REPAIR_JSON"] = json.dumps(repair_instruction or {}, ensure_ascii=False)
    try:
        completed = subprocess.run(
            [python_executable, str(code_path.resolve(strict=False))],
            cwd=str(code_path.parent),
            text=True,
            encoding="utf-8",
            errors="replace",
            capture_output=True,
            env=env,
            timeout=timeout_seconds,
        )
    except subprocess.TimeoutExpired as exc:
        return CodeExecutionResult(
            returncode=None,
            stdout=exc.stdout or "",
            stderr=(exc.stderr or "") + f"\nExecution timed out after {timeout_seconds} seconds.",
            timed_out=True,
        )
    except Exception as exc:
        return CodeExecutionResult(returncode=None, stdout="", stderr=f"Execution failed: {exc}")
    return CodeExecutionResult(returncode=completed.returncode, stdout=completed.stdout, stderr=completed.stderr)


