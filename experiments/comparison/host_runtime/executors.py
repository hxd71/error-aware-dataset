@dataclass(frozen=True)
class CodeExecutionResult:
    returncode: int | None
    stdout: str
    stderr: str
    timed_out: bool = False

    def to_log(self) -> str:
        lines = [
            f"returncode={self.returncode}",
            f"timed_out={self.timed_out}",
            "[stdout]",
            self.stdout.strip(),
            "[stderr]",
            self.stderr.strip(),
        ]
        return "\n".join(lines).strip() + "\n"


@dataclass(frozen=True)
class CodeGenerationResult:
    code: str
    token_usage: dict[str, int]


class CodeGenerationError(RuntimeError):
    def __init__(self, message: str, token_usage: dict[str, int] | None = None) -> None:
        super().__init__(message)
        self.token_usage = token_usage or _zero_token_usage()


class ExecutorBackend:
    backend_name = "abstract"
    backend_version = "0.0.0"

    def generate_code(
        self,
        *,
        task: BenchmarkTask,
        agent_kind: AgentKind,
        attempt_index: int,
        repair_instruction: dict[str, Any] | None,
        previous_code: str,
        previous_execution_log: str,
    ) -> str:
        raise NotImplementedError

    def generate_code_with_usage(
        self,
        *,
        task: BenchmarkTask,
        agent_kind: AgentKind,
        attempt_index: int,
        repair_instruction: dict[str, Any] | None,
        previous_code: str,
        previous_execution_log: str,
    ) -> CodeGenerationResult:
        code = self.generate_code(
            task=task,
            agent_kind=agent_kind,
            attempt_index=attempt_index,
            repair_instruction=repair_instruction,
            previous_code=previous_code,
            previous_execution_log=previous_execution_log,
        )
        return CodeGenerationResult(code=code, token_usage=_zero_token_usage())

    def run_code(
        self,
        *,
        code_path: Path,
        output_path: Path,
        task: BenchmarkTask,
        repair_instruction: dict[str, Any] | None,
        previous_output_path: Path | None = None,
    ) -> CodeExecutionResult:
        raise NotImplementedError


class MockExecutorBackend(ExecutorBackend):
    backend_name = "mock_executor"
    backend_version = "0.1.0"

    def __init__(self, python_executable: str | None = None, timeout_seconds: int = 60) -> None:
        self.python_executable = python_executable or sys.executable
        self.timeout_seconds = timeout_seconds

    def generate_code(
        self,
        *,
        task: BenchmarkTask,
        agent_kind: AgentKind,
        attempt_index: int,
        repair_instruction: dict[str, Any] | None,
        previous_code: str,
        previous_execution_log: str,
    ) -> str:
        repair_mode = repair_instruction.get("mode", "none") if repair_instruction else "none"
        return "\n".join(
            [
                "# Mock GIS workflow generated by the shared multi-agent host.",
                "import json",
                "import os",
                f"TASK_ID = {task.task_id!r}",
                f"AGENT_KIND = {agent_kind!r}",
                f"ATTEMPT_INDEX = {attempt_index!r}",
                f"REPAIR_MODE = {repair_mode!r}",
                "def main():",
                "    output_dir = os.environ.get('OUTPUT_DIR', '.')",
                "    os.makedirs(output_dir, exist_ok=True)",
                "    with open(os.path.join(output_dir, 'result_stub.json'), 'w', encoding='utf-8') as f:",
                "        json.dump({'task_id': TASK_ID, 'agent_kind': AGENT_KIND, 'attempt_index': ATTEMPT_INDEX, 'repair_mode': REPAIR_MODE}, f, ensure_ascii=False, indent=2)",
                "    with open(os.path.join(output_dir, 'workflow_steps.json'), 'w', encoding='utf-8') as f:",
                "        json.dump({'schema_version': '0.1.0', 'status': 'reported', 'steps': [{'step_id': 'step_01', 'name': 'mock_output', 'status': 'completed', 'outputs': ['result_stub.json'], 'gis_invariants_checked': [], 'observations': ['mock execution completed'], 'suspected_issue': ''}]}, f, ensure_ascii=False, indent=2)",
                "    return {'status': 'mock-output'}",
                "",
                "if __name__ == '__main__':",
                "    main()",
                "",
            ]
        )

    def run_code(
        self,
        *,
        code_path: Path,
        output_path: Path,
        task: BenchmarkTask,
        repair_instruction: dict[str, Any] | None,
        previous_output_path: Path | None = None,
    ) -> CodeExecutionResult:
        return _run_python_code(
            python_executable=self.python_executable,
            code_path=code_path,
            output_path=output_path,
            task=task,
            repair_instruction=repair_instruction,
            previous_output_path=previous_output_path,
            timeout_seconds=self.timeout_seconds,
        )


